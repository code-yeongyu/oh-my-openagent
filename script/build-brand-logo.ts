import { renameSync } from "node:fs"
import { fileURLToPath } from "node:url"

// The engine shows the brand logo on the provider sign-in result page (SENPI_BRAND `logo`, a base64
// image data URI). Every launch path imports this one generated module, so they cannot drift apart
// or away from the canonical icon.
const root = fileURLToPath(new URL("..", import.meta.url))
const source = `${root}.github/assets/omo-icon-light.svg`
const target = `${root}packages/omo-native/bin/lib/brand-logo.generated.js`

/** The module text for an icon. Line endings are normalized to LF, so a CRLF checkout yields the same module. */
export function brandLogoModule(svg: string): string {
  const icon = Buffer.from(svg.replaceAll("\r\n", "\n"), "utf8").toString("base64")
  return [
    "// Generated by bun script/build-brand-logo.ts from .github/assets/omo-icon-light.svg; do not edit.",
    "/** The OmO icon as a base64 SVG data URI: the `logo` every launcher puts in SENPI_BRAND. */",
    `export const OMO_BRAND_LOGO = "data:image/svg+xml;base64,${icon}"`,
    "",
  ].join("\n")
}

// The output path is a parameter so a test can build into a throwaway file instead of the shared module.
export async function buildBrandLogo(check = false, output = target): Promise<void> {
  const text = brandLogoModule(await Bun.file(source).text())
  const current = (await Bun.file(output).exists()) ? await Bun.file(output).text() : undefined
  if (check) {
    if (current !== text) throw new Error("Brand logo module is stale; run bun script/build-brand-logo.ts")
    return
  }
  // The root build bundles the CLIs from this module while build-install.mjs regenerates it, so an unchanged module is
  // left alone and a changed one is replaced in one rename, never truncated in place.
  if (current === text) return
  const temporary = `${output}.${process.pid}.tmp`
  await Bun.write(temporary, text)
  renameSync(temporary, output)
}

if (import.meta.main) {
  await buildBrandLogo(process.argv.includes("--check"))
  console.log("Brand logo module is current.")
}
