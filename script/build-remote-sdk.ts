import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

// `omo-ai/remote` (omo#13413): the remote module bundled for node plus its declaration tree. TypeScript 7 has no
// JS compiler API, so no d.ts bundler runs here: tsgo emits the tree the entry's types reach, with the private
// device-service-core package mapped to its source so it is emitted too, and its bare specifier rewritten relative.

const root = fileURLToPath(new URL("..", import.meta.url))
const packages = join(root, "packages")
const lib = join(packages, "omo-native", "bin", "lib")
const HEADER = "// Generated by bun script/build-remote-sdk.ts; do not edit.\n"
const CORE = "@oh-my-opencode/device-service-core"
const TYPES_DIR = "remote-sdk-types"

type Artifacts = Map<string, string>

async function bundle(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(packages, "omo-native", "remote-sdk.ts")],
    target: "node",
    format: "esm",
    minify: { whitespace: true, syntax: true },
  })
  if (!result.success) throw new Error("Remote SDK bundle failed", { cause: result.logs })
  const output = result.outputs[0]
  if (!output) throw new Error("Remote SDK bundle was not produced")
  return `${HEADER}${await output.text()}`
}

const walk = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)],
  )

function relink(file: string, text: string, typesRoot: string): string {
  const core = join(typesRoot, "device-service-core", "src", "index.js")
  let target = relative(dirname(file), core)
  if (!target.startsWith(".")) target = `./${target}`
  return text.replaceAll(`"${CORE}"`, `"${target}"`).replace(/(from "\.{1,2}\/[^"]*)\.ts"/g, '$1.js"')
}

async function declarations(): Promise<Artifacts> {
  const scratch = mkdtempSync(join(tmpdir(), "omo-remote-sdk-dts-"))
  try {
    const out = join(scratch, "out")
    const config = join(scratch, "tsconfig.json")
    writeFileSync(
      config,
      JSON.stringify({
        compilerOptions: {
          declaration: true,
          emitDeclarationOnly: true,
          allowImportingTsExtensions: true,
          skipLibCheck: true,
          strict: true,
          module: "esnext",
          moduleResolution: "bundler",
          target: "esnext",
          resolveJsonModule: true,
          types: ["bun-types"],
          typeRoots: [join(root, "node_modules", "@types"), join(root, "node_modules")],
          rootDir: packages,
          outDir: out,
          paths: { [CORE]: [join(packages, "device-service-core", "src", "index.ts")] },
        },
        files: [join(packages, "omo-native", "remote-sdk.ts")],
      }),
    )
    const tsgo = Bun.spawn([join(root, "node_modules", ".bin", "tsgo"), "-p", config], {
      cwd: root,
      stdout: "pipe",
      stderr: "pipe",
    })
    const [stdout, stderr, code] = await Promise.all([
      new Response(tsgo.stdout).text(),
      new Response(tsgo.stderr).text(),
      tsgo.exited,
    ])
    if (code !== 0) throw new Error(`tsgo declaration emit failed (${code}):\n${stdout}${stderr}`)
    const typesRoot = join(lib, TYPES_DIR)
    const artifacts: Artifacts = new Map()
    for (const file of walk(out)) {
      const target = join(typesRoot, relative(out, file))
      artifacts.set(target, `${HEADER}${relink(target, readFileSync(file, "utf8"), typesRoot)}`)
    }
    artifacts.set(
      join(lib, "remote-sdk.generated.d.ts"),
      `${HEADER}export * from "./${TYPES_DIR}/omo-native/remote-sdk.js"\n`,
    )
    return artifacts
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }
}

export async function buildRemoteSdk(check = false): Promise<void> {
  const artifacts = await declarations()
  artifacts.set(join(lib, "remote-sdk.generated.js"), await bundle())
  if (check) {
    const tracked = new Set(walk(join(lib, TYPES_DIR)))
    const stale = [...artifacts].filter(([path, text]) => {
      tracked.delete(path)
      const file = Bun.file(path)
      return file.size === 0 || readFileSync(path, "utf8") !== text
    })
    if (stale.length > 0 || tracked.size > 0) {
      throw new Error("Remote SDK bundle is stale; run bun script/build-remote-sdk.ts")
    }
    return
  }
  rmSync(join(lib, TYPES_DIR), { recursive: true, force: true })
  for (const [path, text] of artifacts) await Bun.write(path, text)
}

if (import.meta.main) {
  await buildRemoteSdk(process.argv.includes("--check"))
  console.log("Remote SDK bundle is current.")
}
