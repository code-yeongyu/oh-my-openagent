import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import nodePath, { dirname, join, relative, resolve, sep } from "node:path"
import { fileURLToPath } from "node:url"

// `omo-ai/remote` (omo#13413): the remote module bundled for node plus its declaration tree. TypeScript 7 has no
// JS compiler API, so no d.ts bundler runs here: tsgo emits the tree the public surface (remote-sdk-api.ts) reaches,
// with the private device-service-core package mapped to its source so it is emitted too. Every specifier is then
// rewritten to the emitted file it names, with the `.js` a node ESM consumer needs, and a tree that still imports
// anything but `node:` built-ins is refused: the published types must resolve from omo-ai alone.

const root = fileURLToPath(new URL("..", import.meta.url))
const packages = join(root, "packages")
const lib = join(packages, "omo-native", "bin", "lib")
const HEADER = "// Generated by bun script/build-remote-sdk.ts; do not edit.\n"
const CORE = "@oh-my-opencode/device-service-core"
const TYPES_DIR = "remote-sdk-types"
const API_ENTRY = join(packages, "omo-native", "remote-sdk-api.ts")
const SPECIFIER = /(from\s+|import\s*\(\s*)(["'])([^"']+)\2/g
const TYPES_REFERENCE = /\/\/\/\s*<reference\s+types="([^"]+)"\s*\/>/g

/** device-service-core's export map as `paths`: each subpath to its source file. */
const coreExports = (): Record<string, string> => {
  const manifest: { readonly exports: Record<string, string> } = JSON.parse(
    readFileSync(join(packages, "device-service-core", "package.json"), "utf8"),
  )
  return Object.fromEntries(
    Object.entries(manifest.exports).map(([key, file]) => [
      key === "." ? CORE : `${CORE}/${key.slice(2)}`,
      join(packages, "device-service-core", file),
    ]),
  )
}

type Artifacts = Map<string, string>

async function bundle(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(packages, "omo-native", "remote-sdk.ts")],
    target: "node",
    format: "esm",
    minify: { whitespace: true, syntax: true },
  })
  if (!result.success) throw new Error("Remote SDK bundle failed", { cause: result.logs })
  const output = result.outputs[0]
  if (!output) throw new Error("Remote SDK bundle was not produced")
  return `${HEADER}${await output.text()}`
}

const walk = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)],
  )

const declarationOf = (out: string, source: string): string =>
  join(out, relative(packages, source)).replace(/\.ts$/, ".d.ts")

/** The emitted declaration a specifier of `file` names, or undefined when it names nothing in the tree. */
function emittedTarget(out: string, file: string, specifier: string, core: Record<string, string>): string | undefined {
  const mapped = core[specifier]
  if (mapped !== undefined) return declarationOf(out, mapped)
  if (!specifier.startsWith(".")) return undefined
  const base = resolve(dirname(file), specifier.replace(/\.(d\.ts|ts|js)$/, ""))
  return [`${base}.d.ts`, join(base, "index.d.ts")].find((candidate) => existsSync(candidate))
}

function relink(out: string, file: string, text: string, core: Record<string, string>): string {
  const unresolved: string[] = []
  for (const [, name] of text.matchAll(TYPES_REFERENCE)) if (name !== "node") unresolved.push(`types="${name}"`)
  const linked = text.replace(SPECIFIER, (whole, lead: string, quote: string, specifier: string) => {
    if (specifier.startsWith("node:")) return whole
    const target = emittedTarget(out, file, specifier, core)
    if (target === undefined) {
      unresolved.push(specifier)
      return whole
    }
    // A module specifier uses "/" on every OS; a Windows separator would turn `.\remote...` into an escape sequence.
    const path = relative(dirname(file), target)
      .split(sep)
      .join("/")
      .replace(/\.d\.ts$/, ".js")
    return `${lead}${quote}${path.startsWith(".") ? path : `./${path}`}${quote}`
  })
  if (unresolved.length > 0)
    throw new Error(
      `${relative(out, file)} imports ${unresolved.join(", ")}: the omo-ai/remote types must resolve from omo-ai alone`,
    )
  return linked
}

async function declarations(): Promise<Artifacts> {
  const scratch = mkdtempSync(join(tmpdir(), "omo-remote-sdk-dts-"))
  const core = coreExports()
  try {
    const out = join(scratch, "out")
    const config = join(scratch, "tsconfig.json")
    writeFileSync(
      config,
      JSON.stringify({
        compilerOptions: {
          declaration: true,
          emitDeclarationOnly: true,
          // Emit only: the package's own typecheck (packages/omo-native/tsconfig.json) proves these types. Checking here
          // would re-check the whole graph the factories reach under preserveSymlinks, where unrelated modules resolve apart.
          noCheck: true,
          allowImportingTsExtensions: true,
          skipLibCheck: true,
          strict: true,
          module: "esnext",
          moduleResolution: "bundler",
          target: "esnext",
          resolveJsonModule: true,
          // Without it tsgo realpaths workspace links concurrently and, depending on which resolution wins, treats part of
          // device-service-core as an external library and skips its declarations: a different tree on every run.
          preserveSymlinks: true,
          types: ["bun-types"],
          typeRoots: [join(root, "node_modules", "@types"), join(root, "node_modules")],
          rootDir: packages,
          outDir: out,
          paths: Object.fromEntries(Object.entries(core).map(([specifier, file]) => [specifier, [file]])),
        },
        files: [API_ENTRY],
      }),
    )
    const tsgo = Bun.spawn([join(root, "node_modules", ".bin", "tsgo"), "-p", config], {
      cwd: root,
      stdout: "pipe",
      stderr: "pipe",
    })
    const [stdout, stderr, code] = await Promise.all([
      new Response(tsgo.stdout).text(),
      new Response(tsgo.stderr).text(),
      tsgo.exited,
    ])
    if (code !== 0) throw new Error(`tsgo declaration emit failed (${code}):\n${stdout}${stderr}`)
    const typesRoot = join(lib, TYPES_DIR)
    const artifacts: Artifacts = new Map()
    for (const file of walk(out))
      artifacts.set(
        join(typesRoot, relative(out, file)),
        `${HEADER}${relink(out, file, readFileSync(file, "utf8"), core)}`,
      )
    artifacts.set(
      join(lib, "remote-sdk.generated.d.ts"),
      `${HEADER}export * from "./${TYPES_DIR}/omo-native/remote-sdk-api.js"\n`,
    )
    return artifacts
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }
}

/**
 * Every path where what a commit ships differs from the build: an artifact git's index does not hold (missing, or written
 * but never added), one whose indexed bytes differ, or an indexed file in the types tree the build no longer emits. The
 * working tree is never read: an install's prepare build rewrites it, so it would always look current. Every key and
 * `typesRoot` come from `paths` (the platform's path module), so the types tree is judged with it too.
 */
export function staleArtifacts(
  artifacts: ReadonlyMap<string, string>,
  typesRoot: string,
  indexed: ReadonlyMap<string, string>,
  paths: typeof nodePath = nodePath,
): string[] {
  const inTypes = (file: string): boolean => {
    const below = paths.relative(typesRoot, file)
    return below !== "" && below !== ".." && !below.startsWith(`..${paths.sep}`) && !paths.isAbsolute(below)
  }
  const extra = new Set([...indexed.keys()].filter(inTypes))
  const differing = [...artifacts]
    .filter(([path, text]) => {
      extra.delete(path)
      return indexed.get(path) !== text
    })
    .map(([path]) => path)
  return [...differing, ...extra]
}

async function git(repo: string, args: readonly string[], input?: string): Promise<Buffer> {
  const run = Bun.spawn(["git", ...args], {
    cwd: repo,
    stdin: input === undefined ? "ignore" : new TextEncoder().encode(input),
    stdout: "pipe",
    stderr: "pipe",
  })
  const [stdout, stderr, code] = await Promise.all([
    new Response(run.stdout).arrayBuffer(),
    new Response(run.stderr).text(),
    run.exited,
  ])
  if (code !== 0) throw new Error(`git ${args[0]} failed (${code}): ${stderr}`)
  return Buffer.from(stdout)
}

/** The bytes git's index holds for every file under `dir`, keyed by absolute path: what a commit ships. */
export async function indexedFiles(repo: string, dir: string): Promise<Map<string, string>> {
  // `ls-files -s -z`: "<mode> <blob> <stage>\t<path>" per entry; the blobs' bytes come back from one cat-file batch.
  const entries = (await git(repo, ["ls-files", "-s", "-z", "--", relative(repo, dir)]))
    .toString("utf8")
    .split("\0")
    .filter((entry) => entry !== "")
    .map((entry) => {
      const tab = entry.indexOf("\t")
      return { blob: entry.slice(0, tab).split(" ")[1] ?? "", path: join(repo, entry.slice(tab + 1)) }
    })
  if (entries.length === 0) return new Map()
  const batch = await git(repo, ["cat-file", "--batch"], `${entries.map((e) => e.blob).join("\n")}\n`)
  const indexed = new Map<string, string>()
  let at = 0
  for (const { path } of entries) {
    const header = batch.indexOf(0x0a, at)
    const size = Number(batch.subarray(at, header).toString("utf8").split(" ")[2])
    indexed.set(path, batch.subarray(header + 1, header + 1 + size).toString("utf8"))
    at = header + 1 + size + 1
  }
  return indexed
}

export async function buildRemoteSdk(check = false): Promise<void> {
  const artifacts = await declarations()
  artifacts.set(join(lib, "remote-sdk.generated.js"), await bundle())
  if (check) {
    const stale = staleArtifacts(artifacts, join(lib, TYPES_DIR), await indexedFiles(root, lib))
    if (stale.length > 0) {
      const listed = stale.map((path) => relative(root, path)).join("\n  ")
      throw new Error(`Remote SDK bundle is stale; run bun script/build-remote-sdk.ts\n  ${listed}`)
    }
    return
  }
  rmSync(join(lib, TYPES_DIR), { recursive: true, force: true })
  for (const [path, text] of artifacts) await Bun.write(path, text)
}

if (import.meta.main) {
  await buildRemoteSdk(process.argv.includes("--check"))
  console.log("Remote SDK bundle is current.")
}
