import { fileURLToPath } from "node:url"
import { assertReleaseKeySet } from "./service-auth-release-key"

const root = fileURLToPath(new URL("..", import.meta.url))

export async function buildServiceAuth(check = false, out?: string): Promise<void> {
  const target = out ?? `${root}packages/omo-native/bin/lib/service-auth.generated.js`
  const result = await Bun.build({
    entrypoints: [`${root}packages/omo-native/launcher-commands.ts`],
    target: "node",
    format: "esm",
    minify: { whitespace: true, syntax: true },
  })
  if (!result.success) throw new Error("Service auth bundle failed", { cause: result.logs })
  const output = result.outputs[0]
  if (!output) throw new Error("Service auth bundle was not produced")
  const text = `// Generated by bun script/build-service-auth.ts; do not edit.\n${await output.text()}`
  assertReleaseKeySet(text)
  if (check) {
    if (out !== undefined) throw new Error("--check and --out are separate invocations")
    if (!(await Bun.file(target).exists()) || (await Bun.file(target).text()) !== text) {
      throw new Error("Service auth bundle is stale; run bun script/build-service-auth.ts")
    }
  } else {
    await Bun.write(target, text)
  }
}

if (import.meta.main) {
  const outIndex = process.argv.indexOf("--out")
  await buildServiceAuth(process.argv.includes("--check"), outIndex === -1 ? undefined : process.argv[outIndex + 1])
  console.log("Service auth bundle is current.")
}
