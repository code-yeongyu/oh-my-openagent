import { describe, expect, test } from "bun:test"
import { createHash } from "node:crypto"
import { readFileSync } from "node:fs"
import { resolve } from "node:path"
import { publicKeyText } from "../recovery/derive.ts"
import { derivePhraseKeys, generateRecoveryPhrase } from "../recovery/phrase.ts"
import { parseBody } from "./parse.ts"
import { FIXTURES } from "./testing/sync-v1.test-support.ts"
import type { KeyringBody } from "./entry.ts"
import { recomputeForkState } from "./vendor/sync-format/fold.ts"
import { type ChainEntry, receiveKeyringChain } from "./vendor/sync-format/index.ts"
import { b64urlDecode } from "./vendor/sync-format/jcs.ts"

// A3 M6: the service's own phrase vectors (omo-service #1068 fixtures/sync-v1/phrase-chain.json, generated by
// its gen/phrase.mjs) read by THIS engine. A local-only fork test cannot catch the service fold and the vendored
// fold disagreeing on a phrase key (the r1 fork_state_mismatch lockout); this file can.
const PHRASE_CHAIN_SHA256 = "86552b0f1402343982fa427fc05e623a129fdfa6d7b396251db4e557b3e5c5ac"

type Record_ = ChainEntry & { readonly body: KeyringBody }
type PhraseKey = {
  readonly entropy: string
  readonly enrollment_nonce: string
  readonly sealing_public_key: string
  readonly signing_public_key: string
}
type Fixture = {
  readonly account: string
  readonly derivation: { readonly keys: Readonly<Record<string, PhraseKey>> }
  readonly main: ReadonlyArray<string>
  readonly branches: { readonly fork: ReadonlyArray<string> }
  readonly records: Readonly<Record<string, Record_>>
  readonly refused: Readonly<
    Record<string, { readonly reason: string; readonly request: { readonly record: KeyringBody } }>
  >
}

const bytes = readFileSync(resolve(FIXTURES, "phrase-chain.json"))
const fixture: Fixture = JSON.parse(bytes.toString("utf8"))
const record = (name: string): Record_ => {
  const found = fixture.records[name]
  if (found === undefined) throw new Error(`fixture missing ${name}`)
  return found
}
const main = () => fixture.main.map(record)
const forked = () => [...main(), ...fixture.branches.fork.map(record)]

describe("omo-service phrase vectors (#1068) read by the engine", () => {
  // Supply-chain contract: vendored vectors come from a MERGED service commit, never an open PR head.
  test("the vendored phrase vectors are pinned to omo-service main after #1068 merged, not to the PR head", () => {
    const manifest = JSON.parse(readFileSync(resolve(FIXTURES, "../../manifest.json"), "utf8"))
    expect(manifest.source.pending_upstream).toBeUndefined()
    expect(manifest.source.files_at).toEqual({
      commit: "45f13ee1e361b6f7a385ef85cb011a6dceddd691",
      files: ["fixtures/sync-v1/phrase-chain.json"],
      reason: "phrase vectors (A3 M6), vendored from main at the merge of #1068",
    })
  })

  test("the vendored file is the pinned service file, byte for byte", () => {
    expect(createHash("sha256").update(bytes).digest("hex")).toBe(PHRASE_CHAIN_SHA256)
  })

  test("the engine derives the service's phrase public keys from the same entropy, account and nonce", async () => {
    const keys = Object.values(fixture.derivation.keys)
    expect(keys.length).toBe(2)
    for (const key of keys) {
      const entropy = b64urlDecode(key.entropy)
      const phrase = generateRecoveryPhrase((target) => void target.set(entropy))
      const derived = publicKeyText(await derivePhraseKeys(phrase, fixture.account, b64urlDecode(key.enrollment_nonce)))
      phrase.dispose()
      expect(derived).toEqual({
        sealing_public_key: key.sealing_public_key,
        signing_public_key: key.signing_public_key,
      })
    }
  })

  test("the phrase genesis and enrollment parse as phrase keys and the vendored receiver keeps both phrase", async () => {
    for (const entry of main()) expect(parseBody(entry.body)).not.toBeNull()
    const received = await receiveKeyringChain(main())
    expect(received.ok).toBe(true)
    if (!received.ok) return
    expect([...received.fold.registry.values()].map((key) => key.survivable)).toEqual(["phrase", "phrase"])
  })

  test("the service's fork resolution over phrase keys verifies here and keeps survivable phrase", async () => {
    const resolution = forked().at(-1)
    if (resolution?.body.kind !== "fork-resolution") throw new Error("fixture branch ends unresolved")
    expect(parseBody(resolution.body)).not.toBeNull()
    const { evidence, state } = resolution.body
    if (evidence === undefined || state === undefined) throw new Error("fixture has no evidence")
    expect(recomputeForkState(main(), evidence)).toEqual(state)
    const received = await receiveKeyringChain(forked())
    expect(received.ok).toBe(true)
    if (!received.ok) return
    expect([...received.fold.registry.values()].map((key) => key.survivable)).toEqual(["phrase", "phrase"])
  })

  test("the three requests the service refuses are refused by the engine parser too", () => {
    const refused = Object.entries(fixture.refused)
    expect(refused.length).toBe(3)
    for (const [name, { request }] of refused) expect(parseBody(request.record), name).toBeNull()
  })
})
