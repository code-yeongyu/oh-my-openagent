function Install-Omo {
  param([string]$Target)
  $ErrorActionPreference = 'Stop'
  $ProgressPreference = 'SilentlyContinue' # Invoke-WebRequest is many times slower with the progress bar on 5.1
  $GitHubDownload = 'https://github.com/code-yeongyu/oh-my-openagent/releases/download'
  $NpmDistTags = 'https://registry.npmjs.org/-/package/omo-ai/dist-tags'
  $UserAgent = 'omo-install.ps1/1'
  if ($env:OMO_INSTALL_QA -eq '1') { $UserAgent += ' omo-install-qa' } # QA runs stay out of the public count

  function Write-OmoSay([string]$Message) { Write-Host $Message }
  # omo release signature (#14916): keys + V_SIGN are generated into these constants by
  # script/installer/generate-installer-keys.ts; empty means signing is inactive and nothing is verified.
  $script:OmoReleaseKeys = @()
  $script:OmoReleaseVSign = ''

  function Compare-OmoVersion([string]$Left, [string]$Right) {
    $a = $Left.Split('-')[0].Split('.')
    $b = $Right.Split('-')[0].Split('.')
    for ($i = 0; $i -lt 3; $i++) {
      $cmp = ([int]$a[$i]) - ([int]$b[$i])
      if ($cmp -ne 0) { return $cmp }
    }
    $la = $Left.Contains('-'); $lb = $Right.Contains('-')
    if ($la -and -not $lb) { return -1 }
    if (-not $la -and $lb) { return 1 }
    return 0
  }

  function Get-OmoReleaseVerifier() {
    if (-not ('MinisignEd' -as [type])) {
      $bytes = [Convert]::FromBase64String(($OmoVerifierPayload -replace '\s', ''))
      $inStream = New-Object IO.MemoryStream(, $bytes)
      $gz = New-Object IO.Compression.GzipStream($inStream, [IO.Compression.CompressionMode]::Decompress)
      $out = New-Object IO.MemoryStream
      $gz.CopyTo($out)
      $source = [Text.Encoding]::UTF8.GetString($out.ToArray())
      Add-Type -TypeDefinition $source
    }
  }

  function Test-OmoReleaseSignature([string]$SumsPath, [string]$SigPath, [string]$Version, [bool]$ExplicitPin) {
    if ($script:OmoReleaseKeys.Count -eq 0) { return }
    if (-not (Test-Path -LiteralPath $SigPath)) {
      if ($ExplicitPin -and ((Compare-OmoVersion $Version $script:OmoReleaseVSign) -lt 0)) {
        Write-OmoSay "  release $Version predates signed releases; continuing without a signature"
        return
      }
      Stop-OmoInstall "release signature missing (SHA256SUMS.sig); refusing to install. Only an explicitly pinned version older than V_sign may be unsigned"
    }
    Get-OmoReleaseVerifier
    $lines = @(Get-Content -LiteralPath $SigPath)
    if ($lines.Count -ne 4) { Stop-OmoInstall 'release signature malformed (line count)' }
    $block = [Convert]::FromBase64String($lines[1])
    if ($block.Length -ne 74) { Stop-OmoInstall 'release signature malformed (length)' }
    if ([Text.Encoding]::ASCII.GetString($block, 0, 2) -ne 'ED') { Stop-OmoInstall 'release signature algorithm refused (only ED is accepted)' }
    $sigKeyid = ([BitConverter]::ToString($block, 2, 8)).Replace('-', '').ToLowerInvariant()
    $sig = New-Object byte[] 64
    [Array]::Copy($block, 10, $sig, 0, 64)
    $sumsBytes = [IO.File]::ReadAllBytes($SumsPath)
    foreach ($entry in $script:OmoReleaseKeys) {
      $parts = $entry.Split('|')
      if ($parts[0] -ne $sigKeyid) { continue }
      $spki = [Convert]::FromBase64String($parts[1])
      if ($spki.Length -ne 44) { continue }
      $pk = New-Object byte[] 32
      [Array]::Copy($spki, 12, $pk, 0, 32)
      if ([MinisignEd]::Verify($pk, $sig, $sumsBytes)) {
        Write-OmoSay "  release signature verified (key $($parts[0]))"
        return
      }
    }
    Stop-OmoInstall 'release signature invalid; refusing to install (possible tampering)'
  }

