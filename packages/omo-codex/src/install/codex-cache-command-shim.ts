export const COMMAND_SHIM_MARKER = ":: generated by oh-my-openagent Codex installer"

/**
 * Node discovery for the generated .cmd files. Delayed expansion stays OFF: under it `!` is a variable delimiter,
 * so a Node path or an argument containing `!` was silently corrupted (#11230). Every step is therefore a single
 * line read with percent expansion, and each substring step runs only after a guard proves the value is defined
 * (percent substitution on an undefined variable does not expand to an empty string).
 */
export function windowsNodeDiscoveryLines(): string[] {
  const skip = "if not defined OMO_NODE_BINARY goto omo_node_from_path"
  return [
    "setlocal EnableExtensions DisableDelayedExpansion",
    'set "OMO_NODE_BINARY="',
    'set "OMO_NODE_REPL_NODE_PATH=%NODE_REPL_NODE_PATH%"',
    'if exist "%CODEX_HOME%\\config.toml" (',
    '  for /f "tokens=1,* delims==" %%A in (\'findstr /R /C:"NODE_REPL_NODE_PATH[ ]*=" "%CODEX_HOME%\\config.toml" 2^>nul\') do (',
    '    set "OMO_NODE_REPL_NODE_PATH=%%B"',
    "  )",
    ")",
    "if not defined OMO_NODE_REPL_NODE_PATH goto omo_node_from_path",
    // A Windows path cannot contain a double quote, so dropping every one strips TOML's basic-string quoting.
    'set "OMO_NODE_BINARY=%OMO_NODE_REPL_NODE_PATH:"=%"',
    skip,
    'for /f "tokens=* delims= " %%N in ("%OMO_NODE_BINARY%") do set "OMO_NODE_BINARY=%%N"',
    skip,
    // A literal string's single quotes are stripped only at the ends: a path may contain one (O'Brien).
    `if "%OMO_NODE_BINARY:~0,1%"=="'" set "OMO_NODE_BINARY=%OMO_NODE_BINARY:~1%"`,
    skip,
    `if "%OMO_NODE_BINARY:~-1%"=="'" set "OMO_NODE_BINARY=%OMO_NODE_BINARY:~0,-1%"`,
    skip,
    'if not exist "%OMO_NODE_BINARY%" set "OMO_NODE_BINARY="',
    ":omo_node_from_path",
    'if not defined OMO_NODE_BINARY where node >nul 2>nul && set "OMO_NODE_BINARY=node"',
  ]
}

export function windowsCommandShim(targetPath: string): string {
  return [
    "@echo off",
    COMMAND_SHIM_MARKER,
    'if not defined CODEX_HOME set "CODEX_HOME=%USERPROFILE%\\.codex"',
    ...windowsNodeDiscoveryLines(),
    "if not defined OMO_NODE_BINARY (",
    "  echo omo: no Node runtime was discovered from NODE_REPL_NODE_PATH or PATH; rerun LazyCodex install from Codex Desktop 1>&2",
    "  exit /b 127",
    ")",
    `"%OMO_NODE_BINARY%" "${targetPath}" %*`,
    "exit /b %ERRORLEVEL%",
    "",
  ].join("\r\n")
}
