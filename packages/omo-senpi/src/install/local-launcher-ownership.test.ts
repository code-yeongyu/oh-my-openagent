/// <reference types="bun-types" />

import { afterEach, describe, expect, test } from "bun:test"
import {
  existsSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  readlinkSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"

import { runSenpiInstaller, runSenpiUninstaller } from "./install-senpi"
import { createPluginFixture } from "./install-test-fixture"
import {
  installLocalLauncher,
  localLauncherCmdPath,
  localLauncherPath,
  renderLocalLauncher,
  uninstallLocalLauncher,
} from "./local-launcher"

// #13254: the installer replaces or removes ~/.local/bin/omo only when it wrote that file. The compiled omo binary embeds
// the installer's source, so it contains the shim's header text somewhere inside it; ownership must be decided by the
// header at the start of the file, never by a search. Every case runs in a temporary home passed explicitly.
const repoRoot = resolve(import.meta.dir, "../../../..")
const roots: string[] = []

// The header every launcher shipped before #13254 starts with; such shims are still owned.
const LEGACY_HEADER =
  "#!/usr/bin/env node\n// omo-local-launcher: generated by the omo-senpi installer. Delete this file to remove the local launcher.\n"
const CMD_SHIM = `@echo off\r\nnode "%~dp0omo" %*\r\n`
const BASE = { pluginPath: "/repo/packages/omo-senpi/plugin", senpiCliPath: "/repo/senpi/dist/cli.js", version: "9.9.9" }

function scratchHome(): string {
  const home = mkdtempSync(join(tmpdir(), "omo-launcher-ownership-"))
  roots.push(home)
  mkdirSync(join(home, ".local", "bin"), { recursive: true })
  return home
}

afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true })
})

// What a compiled omo looks like to the old check: executable bytes with the installer's header text in the middle.
function compiledBinaryBytes(): Buffer {
  return Buffer.concat([
    Buffer.from([0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01, 0x01, 0x00]),
    Buffer.alloc(4096, 0x90),
    Buffer.from(LEGACY_HEADER),
    Buffer.from(renderLocalLauncher(BASE)),
    Buffer.alloc(4096, 0x00),
  ])
}

type Foreign = { readonly name: string; readonly place: (home: string) => () => void }

const FOREIGN: readonly Foreign[] = [
  {
    name: "a compiled binary whose bytes contain the shim header text",
    place: (home) => {
      const bytes = compiledBinaryBytes()
      writeFileSync(localLauncherPath(home), bytes, { mode: 0o755 })
      return () => expect(readFileSync(localLauncherPath(home)).equals(bytes)).toBe(true)
    },
  },
  {
    name: "a symlink to another launcher",
    place: (home) => {
      const target = join(home, "elsewhere", "omo")
      mkdirSync(join(home, "elsewhere"))
      const bytes = `${LEGACY_HEADER}// another install's own launcher\n`
      writeFileSync(target, bytes, { mode: 0o755 })
      symlinkSync(target, localLauncherPath(home))
      return () => {
        expect(lstatSync(localLauncherPath(home)).isSymbolicLink()).toBe(true)
        expect(readlinkSync(localLauncherPath(home))).toBe(target)
        expect(readFileSync(target, "utf8")).toBe(bytes)
      }
    },
  },
  {
    name: "an unrelated script",
    place: (home) => {
      const bytes = "#!/bin/sh\nexec /opt/other/omo \"$@\"\n"
      writeFileSync(localLauncherPath(home), bytes, { mode: 0o755 })
      return () => expect(readFileSync(localLauncherPath(home), "utf8")).toBe(bytes)
    },
  },
  {
    name: "a file that starts with the shim header but is far larger than any shim",
    place: (home) => {
      const bytes = Buffer.concat([Buffer.from(LEGACY_HEADER), Buffer.alloc(2 * 1024 * 1024, 0x61)])
      writeFileSync(localLauncherPath(home), bytes, { mode: 0o755 })
      return () => expect(readFileSync(localLauncherPath(home)).equals(bytes)).toBe(true)
    },
  },
]

describe("local launcher ownership", () => {
  describe.each(FOREIGN)("#given $name at the launcher path", ({ place }) => {
    test("#when installing #then nothing is written and the file is left as it was", () => {
      // given
      const home = scratchHome()
      const unchanged = place(home)

      // when
      const installed = installLocalLauncher({ ...BASE, homeDir: home })

      // then
      expect(installed).toBeUndefined()
      unchanged()
    })

    test("#when uninstalling #then nothing is removed", () => {
      // given
      const home = scratchHome()
      const unchanged = place(home)

      // when
      const removed = uninstallLocalLauncher(home)

      // then
      expect(removed).toBe(false)
      unchanged()
    })
  })

  // Shims installed before #13254 carry the unversioned header; they stay the installer's own.
  describe.each([
    { name: "a shim written before the header carried a version", header: LEGACY_HEADER },
    { name: "a shim this installer writes now", header: undefined },
  ])("#given $name at the launcher path", ({ header }) => {
    const shim = (home: string) => {
      const current = renderLocalLauncher(BASE)
      const bytes = header === undefined ? current : `${header}${current.slice(current.indexOf("\n", current.indexOf("\n") + 1) + 1)}`
      writeFileSync(localLauncherPath(home), bytes, { mode: 0o755 })
    }

    test("#when installing #then it is replaced by the current shim", () => {
      // given
      const home = scratchHome()
      shim(home)

      // when
      const installed = installLocalLauncher({ ...BASE, homeDir: home, version: "1.2.3" })

      // then
      expect(installed).toBe(localLauncherPath(home))
      expect(readFileSync(localLauncherPath(home), "utf8")).toBe(renderLocalLauncher({ ...BASE, version: "1.2.3" }))
    })

    test("#when uninstalling #then it is removed", () => {
      // given
      const home = scratchHome()
      shim(home)

      // when
      const removed = uninstallLocalLauncher(home)

      // then
      expect(removed).toBe(true)
      expect(existsSync(localLauncherPath(home))).toBe(false)
    })
  })

  describe("#given the Windows wrapper omo.cmd", () => {
    test("#when installing over a foreign omo.cmd #then the wrapper is left as it was", () => {
      // given
      const home = scratchHome()
      writeFileSync(localLauncherCmdPath(home), "@echo off\r\nC:\\other\\omo.exe %*\r\n")

      // when
      installLocalLauncher({ ...BASE, homeDir: home, platform: "win32" })

      // then
      expect(readFileSync(localLauncherCmdPath(home), "utf8")).toBe("@echo off\r\nC:\\other\\omo.exe %*\r\n")
    })

    test("#when installing beside a foreign omo #then no wrapper is written", () => {
      // given
      const home = scratchHome()
      writeFileSync(localLauncherPath(home), compiledBinaryBytes())

      // when
      installLocalLauncher({ ...BASE, homeDir: home, platform: "win32" })

      // then
      expect(existsSync(localLauncherCmdPath(home))).toBe(false)
    })

    test("#when uninstalling an owned omo beside a foreign omo.cmd #then the wrapper is kept", () => {
      // given
      const home = scratchHome()
      installLocalLauncher({ ...BASE, homeDir: home })
      writeFileSync(localLauncherCmdPath(home), "@echo off\r\nC:\\other\\omo.exe %*\r\n")

      // when
      const removed = uninstallLocalLauncher(home)

      // then
      expect(removed).toBe(true)
      expect(readFileSync(localLauncherCmdPath(home), "utf8")).toBe("@echo off\r\nC:\\other\\omo.exe %*\r\n")
    })

    test("#when uninstalling a foreign omo beside our omo.cmd #then both are kept", () => {
      // given
      const home = scratchHome()
      writeFileSync(localLauncherPath(home), compiledBinaryBytes())
      writeFileSync(localLauncherCmdPath(home), CMD_SHIM)

      // when
      const removed = uninstallLocalLauncher(home)

      // then
      expect(removed).toBe(false)
      expect(existsSync(localLauncherPath(home))).toBe(true)
      expect(readFileSync(localLauncherCmdPath(home), "utf8")).toBe(CMD_SHIM)
    })

    test("#when installing and then uninstalling #then the wrapper is written and removed with the launcher", () => {
      // given
      const home = scratchHome()

      // when
      installLocalLauncher({ ...BASE, homeDir: home, platform: "win32" })
      const written = readFileSync(localLauncherCmdPath(home), "utf8")
      const removed = uninstallLocalLauncher(home)

      // then
      expect(written).toBe(CMD_SHIM)
      expect(removed).toBe(true)
      expect(existsSync(localLauncherCmdPath(home))).toBe(false)
    })
  })

  describe("#given the installer's report", () => {
    async function installerContext(home: string) {
      const agentDir = join(home, "agent")
      mkdirSync(agentDir)
      const pluginPath = await createPluginFixture()
      roots.push(pluginPath)
      return { env: { HOME: home, USERPROFILE: home, SENPI_CODING_AGENT_DIR: agentDir }, homeDir: home, repoRoot, pluginPath }
    }

    test("#when install leaves a foreign launcher alone #then the report says so and why", async () => {
      // given
      const home = scratchHome()
      writeFileSync(localLauncherPath(home), compiledBinaryBytes(), { mode: 0o755 })

      // when
      const result = await runSenpiInstaller(await installerContext(home))

      // then
      expect(result.launcherPath).toBeUndefined()
      expect(result.launcherLeftAlone?.path).toBe(localLauncherPath(home))
      expect(result.launcherLeftAlone?.reason).toContain("not a launcher this installer wrote")
    })

    test("#when uninstall leaves a foreign launcher alone #then the report says so", async () => {
      // given
      const home = scratchHome()
      writeFileSync(localLauncherPath(home), compiledBinaryBytes(), { mode: 0o755 })

      // when
      const result = await runSenpiUninstaller(await installerContext(home))

      // then
      expect(existsSync(localLauncherPath(home))).toBe(true)
      expect(result.launcherLeftAlone?.path).toBe(localLauncherPath(home))
    })
  })
})
