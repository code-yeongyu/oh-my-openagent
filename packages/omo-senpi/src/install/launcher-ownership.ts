import { closeSync, lstatSync, openSync, readSync, type Stats } from "node:fs"

/**
 * Whether a file at the launcher path is a shim this installer wrote (#13254).
 *
 * The compiled omo binary embeds the installer's source, so the shim's header text occurs somewhere inside it; a search
 * for that text would claim the binary, and install would overwrite it while uninstall deleted it. What the binary cannot
 * have is the header at offset 0. Ownership is therefore: a regular file (never a symlink), no larger than any shim can
 * be, whose first bytes are exactly one of the shim headers. Only those first bytes are read.
 */
const SHEBANG = "#!/usr/bin/env node\n"
const MARKER_TAIL = ": generated by the omo-senpi installer. Delete this file to remove the local launcher.\n"

/** The header the shim writes now: the shebang, then a marker line that carries the format version. */
export const LAUNCHER_HEADER = `${SHEBANG}// omo-local-launcher v2${MARKER_TAIL}`
/** The header of every shim written before the marker carried a version; such shims are still owned. */
const LEGACY_LAUNCHER_HEADER = `${SHEBANG}// omo-local-launcher${MARKER_TAIL}`
const OWNED_HEADERS = [LAUNCHER_HEADER, LEGACY_LAUNCHER_HEADER].map((header) => Buffer.from(header, "utf8"))

/** The Windows wrapper the installer writes beside the shim; owned only when its bytes are exactly these. */
export const LAUNCHER_CMD_SHIM = `@echo off\r\nnode "%~dp0omo" %*\r\n`
const OWNED_CMD = Buffer.from(LAUNCHER_CMD_SHIM, "utf8")

// A rendered shim is about 10 KB (the inline logo is most of it); a file past this is not one, whatever it starts with.
const MAX_SHIM_BYTES = 64 * 1024

export type LauncherOwnership =
  { readonly kind: "absent" } | { readonly kind: "owned" } | { readonly kind: "foreign"; readonly reason: string }

function readPrefix(path: string, length: number): Buffer {
  const fd = openSync(path, "r")
  try {
    const buffer = Buffer.alloc(length)
    const read = readSync(fd, buffer, 0, length, 0)
    return buffer.subarray(0, read)
  } finally {
    closeSync(fd)
  }
}

function classify(
  path: string,
  isOwned: (prefix: Buffer, size: number) => boolean,
  prefixBytes: number,
  io: { readonly readPrefix: (path: string, length: number) => Buffer },
): LauncherOwnership {
  let stat: Stats
  try {
    stat = lstatSync(path)
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return { kind: "absent" }
    return { kind: "foreign", reason: `it cannot be inspected (${(error as NodeJS.ErrnoException).code ?? "error"})` }
  }
  if (stat.isSymbolicLink()) return { kind: "foreign", reason: "it is a symbolic link to another file" }
  if (!stat.isFile()) return { kind: "foreign", reason: "it is not a regular file" }
  if (stat.size > MAX_SHIM_BYTES)
    return { kind: "foreign", reason: `it is ${stat.size} bytes, larger than any launcher this installer writes` }
  let prefix: Buffer
  try {
    prefix = io.readPrefix(path, prefixBytes)
  } catch (error) {
    return { kind: "foreign", reason: `it cannot be read (${(error as NodeJS.ErrnoException).code ?? "error"})` }
  }
  return isOwned(prefix, stat.size)
    ? { kind: "owned" }
    : { kind: "foreign", reason: "it does not start with this installer's launcher header" }
}

const HEADER_BYTES = Math.max(...OWNED_HEADERS.map((header) => header.length))

// io is a test seam only: no production caller passes it.
export function launcherOwnership(path: string, io = { readPrefix }): LauncherOwnership {
  return classify(
    path,
    (prefix) => OWNED_HEADERS.some((header) => prefix.subarray(0, header.length).equals(header)),
    HEADER_BYTES,
    io,
  )
}

export function launcherCmdOwnership(path: string, io = { readPrefix }): LauncherOwnership {
  return classify(path, (prefix, size) => size === OWNED_CMD.length && prefix.equals(OWNED_CMD), OWNED_CMD.length, io)
}
