// Regenerates src/engine-schema.generated.ts from crates/omo-computer-core/schema/engine.schema.json.
// Run: bun run --cwd packages/omo-computer-protocol generate
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import { type JsonSchema, typeText } from "./schema-to-typescript.ts"

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..")
export const schemaPath = join(packageDir, "../../crates/omo-computer-core/schema/engine.schema.json")
export const generatedPath = join(packageDir, "src/engine-schema.generated.ts")

function record(value: unknown, label: string): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) throw new Error(`${label} is not an object`)
  return Object.fromEntries(Object.entries(value))
}

function schemaOf(value: unknown, label: string): JsonSchema {
  if (typeof value === "boolean") return value
  return record(value, label)
}

function text(value: unknown, label: string): string {
  if (typeof value !== "string") throw new Error(`${label} is not a string`)
  return value
}

function tableRows(
  entries: readonly (readonly [string, Record<string, unknown>])[],
  members: readonly string[],
): string {
  const rows = entries.map(
    ([name, row]) =>
      `\t{ name: ${JSON.stringify(name)}, ${members.map((member) => `${member}: ${JSON.stringify(row[member])}`).join(", ")} },`,
  )
  return `[\n${rows.join("\n")}\n]`
}

function typeMap(entries: readonly (readonly [string, Record<string, unknown>])[], member: string): string {
  const lines = entries.map(
    ([name, row]) => `\t${JSON.stringify(name)}: ${typeText(schemaOf(row[member], `${name}.${member}`), "\t")}`,
  )
  return `{\n${lines.join("\n")}\n}`
}

/** The generated module's exact text for the given schema file text. */
export function renderProtocolModule(schemaText: string): string {
  const schema = record(JSON.parse(schemaText), "engine.schema.json")
  const methods = Object.entries(record(schema.methods, "methods")).map(
    ([name, row]) => [name, record(row, name)] as const,
  )
  const notifications = Object.entries(record(schema.notifications, "notifications")).map(
    ([name, row]) => [name, record(row, name)] as const,
  )
  const definitions = Object.entries(record(schema.$defs, "$defs"))
  const oneshot = record(schema.oneshot, "oneshot")
  const seams = Array.isArray(schema.envSeams)
    ? schema.envSeams.map((seam) => text(record(seam, "envSeam").name, "envSeam.name"))
    : []
  const settings = Array.isArray(schema.settingsTable)
    ? schema.settingsTable.map((row) => record(row, "settings row"))
    : []
  const sha256 = createHash("sha256").update(schemaText).digest("hex")
  const declarations = definitions.map(
    ([name, definition]) => `export type ${name} = ${typeText(schemaOf(definition, name))}`,
  )
  return `// GENERATED by scripts/generate-protocol.ts from crates/omo-computer-core/schema/engine.schema.json.
// Do not edit by hand; run \`bun run --cwd packages/omo-computer-protocol generate\`.

/** sha256 of the schema file this module was generated from; the schema-drift test compares it. */
export const SCHEMA_SHA256 = ${JSON.stringify(sha256)} as const

/** The wire protocol version \`engine.hello\` reports. */
export const PROTOCOL_VERSION = ${JSON.stringify(text(schema.protocolVersion, "protocolVersion"))} as const

/** The ABI line \`engine.hello\` reports, compared by major. */
export const ABI = ${JSON.stringify(text(schema.abi, "abi"))} as const

/** The method table: wire name, effect and exposure. */
export const METHODS = ${tableRows(methods, ["effect", "exposure"])} as const

export type MethodName = (typeof METHODS)[number]["name"]

/** The engine-to-host notifications. */
export const NOTIFICATIONS = ${JSON.stringify(notifications.map(([name]) => name))} as const

/** A one-shot call names a method with this prefix; the aliases do not strip to a method name. */
export const ONESHOT = ${JSON.stringify({ prefix: text(oneshot.prefix, "oneshot.prefix"), aliases: record(oneshot.aliases, "oneshot.aliases") })} as const

/** The environment seams; no other OMO_COMPUTER_* variable is read. */
export const ENV_SEAMS = ${JSON.stringify(seams)} as const

/** The computer.* settings table: key, reader and whether it is a fingerprinted admission key. */
export const SETTINGS_TABLE = ${JSON.stringify(
    settings.map((row) => ({ key: row.key, status: row.status, reader: row.reader, admissionKey: row.admissionKey })),
    null,
    "\t",
  )} as const

${declarations.join("\n\n")}

/** The params type of every method. */
export type MethodParams = ${typeMap(methods, "params")}

/** The result type of every method. */
export type MethodResults = ${typeMap(methods, "result")}

/** The params type of every notification. */
export type NotificationParams = ${typeMap(notifications, "params")}
`
}

if (import.meta.main) {
  writeFileSync(generatedPath, renderProtocolModule(readFileSync(schemaPath, "utf8")))
}
