/**
 * Minimal local renderer contract that replaces the pi-tui Theme type the senpi
 * adapter imported from @code-yeongyu/senpi. The OMP host provides its own theme
 * object at render time; the renderers only need fg()/bold() to build the same
 * diagnostics text. The container is the local Text class (see rendering.ts) —
 * the rendered content stays identical, only the harness type is gone.
 */
