#!/usr/bin/env bun
// Bundles pinned Roboto Mono Regular/Bold Latin subsets for the Figma OG composition.
// Runtime rendering needs neither a font CDN nor a local filesystem on Cloudflare.
import { mkdtemp, rm } from "node:fs/promises"
import { tmpdir } from "node:os"
import path from "node:path"

const root = path.resolve(import.meta.dirname, "..")
const revision = "aa24661a5ba24c8f8a550a16fb13198719fc2c23"
const source = `https://raw.githubusercontent.com/google/fonts/${revision}/ofl/robotomono/RobotoMono%5Bwght%5D.ttf`
const work = await mkdtemp(path.join(tmpdir(), "omo-og-fonts-"))
try {
  const response = await fetch(source, { signal: AbortSignal.timeout(30_000) })
  if (!response.ok) throw new Error(`Font download failed: ${response.status}`)
  const variable = path.join(work, "RobotoMono.ttf")
  await Bun.write(variable, await response.arrayBuffer())
  let out = "// Generated by scripts/generate-og-fonts.mjs - DO NOT EDIT\n"
  out += "// Roboto Mono Latin subsets; SIL OFL in RobotoMono-OFL.txt.\n\n"
  for (const [name, weight] of [
    ["robotoMonoRegular", 400],
    ["robotoMonoBold", 700],
  ]) {
    const instance = path.join(work, `${name}-full.ttf`)
    const subset = path.join(work, `${name}.ttf`)
    await Bun.$`uv run --with fonttools==4.60.1 fonttools varLib.instancer ${variable} ${`wght=${weight}`} --output ${instance}`
    await Bun.$`uv run --with fonttools==4.60.1 pyftsubset ${instance} --unicodes=U+0020-007E --layout-features=kern,liga,calt ${`--output-file=${subset}`} --no-hinting`
    const bytes = await Bun.file(subset).arrayBuffer()
    out += `export const ${name}Base64 =\n  "${Buffer.from(bytes).toString("base64")}"\n\n`
    process.stdout.write(`${name}: ${bytes.byteLength} bytes subset\n`)
  }
  out += `export function decodeFont(base64: string): ArrayBuffer {
  const binary = atob(base64)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
  return bytes.buffer
}
`
  await Bun.write(path.join(root, "lib/og/fonts.ts"), out)
  process.stdout.write("wrote lib/og/fonts.ts\n")
} finally {
  await rm(work, { recursive: true, force: true })
}
