/**
 * Pins a release's engine digests in the package (#13877 review L2): the checksums file beside a
 * prebuild proves integrity only, since whoever can write the binary can write that file too. The
 * release runs this over the checksums file it publishes, and the launcher refuses any prebuild
 * whose sha256 is not the digest pinned here.
 *
 *   bun packages/omo-computer-engine/scripts/pin-release-digests.ts <omo-computer-engine-checksums.txt>
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { parseChecksums } from "../src/checksums.ts"

/** The `src/release-digests.ts` module for `checksums`; throws on anything that is not a checksums file. */
export function renderReleaseDigests(checksums: string): string {
  const parsed = parseChecksums(checksums)
  if (parsed.kind === "invalid") throw new Error(parsed.detail)
  const rows = [...parsed.digests].map(([asset, digest]) => `  ${JSON.stringify(asset)}: ${JSON.stringify(digest)},`)
  return [
    "// Generated by packages/omo-computer-engine/scripts/pin-release-digests.ts from a release's checksums file; never",
    "// hand-edited. Empty until a release pins it: with no digest pinned for a host, no prebuild launches there.",
    "",
    "/** The sha256 of every engine asset the release shipped, by asset name: the launcher's trust anchor. */",
    `export const RELEASE_DIGESTS: Readonly<Record<string, string>> = {\n${rows.join("\n")}\n}`,
    "",
  ].join("\n")
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = process.argv[2]
  if (source === undefined) {
    console.error("usage: pin-release-digests.ts <omo-computer-engine-checksums.txt>")
    process.exit(2)
  }
  const target = fileURLToPath(new URL("../src/release-digests.ts", import.meta.url))
  writeFileSync(target, renderReleaseDigests(readFileSync(source, "utf8")))
}
