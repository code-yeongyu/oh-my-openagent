async function setup(nested = false) {
  const f = await repo()
  if (nested) {
    const inner = await repo()
    await cp(inner.repoRoot, join(f.repoRoot, "inner"), { recursive: true })
  }
  const baseline = await captureBaseline(f.repoRoot)
  const isolationDir = join(f.root, "child")
  await cp(f.repoRoot, isolationDir, { recursive: true })
  const options = { ...f, baseline, isolationDir, id: "test", artifactsDir: join(f.root, "artifacts"), apply: true, mode: "patch" as const }
  return options
}
async function commit(dir: string, name: string, text = `${name}\n`) {
  await writeFile(join(dir, name), text)
  await git(dir, "add", name)
  await git(dir, "commit", "-m", name)
}
async function text(dir: string, name = "tracked") { return readFile(join(dir, name), "utf8") }

test("patch applies child changes and writes readable artifacts and summary", async () => {
  const f = await setup()
  await writeFile(join(f.isolationDir, "tracked"), "child\n")
  const result = await mergeIsolatedChanges(f)
  expect(result.kind).toBe("applied")
  expect(result.changes_applied).toBe(true)
  expect(result.files_changed).toBe(1)
  expect(await text(f.repoRoot)).toBe("child\n")
  expect(await git(f.repoRoot, "status", "--porcelain")).toBe("M tracked")
  expect(await readFile(result.patch_path!, "utf8")).toContain("+child")
  expect(await readFile(result.summary_path, "utf8")).toContain("applied")
})
test("moved context fails closed atomically, retaining patch and git conflict", async () => {
  const f = await setup()
  await writeFile(join(f.isolationDir, "tracked"), "child\n")
  await writeFile(join(f.isolationDir, "new"), "must not land\n")
  await writeFile(join(f.repoRoot, "tracked"), "parent\n")
  const before = await git(f.repoRoot, "diff", "--binary")
  const result = await mergeIsolatedChanges(f)
  expect(result.kind).toBe("not-applied")
  expect(result.changes_applied).toBe(false)
  expect(result.conflict).toContain("patch does not apply")
  expect(result.manual_command).toBe(`git apply --3way ${result.patch_path}`)
  expect(await git(f.repoRoot, "diff", "--binary")).toBe(before)
  expect(await git(f.repoRoot, "ls-files", "--others", "--exclude-standard")).toBe("")
  expect(await readFile(result.patch_path!, "utf8")).toContain("must not land")
})
