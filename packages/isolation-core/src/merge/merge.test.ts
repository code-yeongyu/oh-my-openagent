test("branch stashes staged, unstaged and untracked parent WIP and restores byte-identically", async () => {
  const f = await setup()
  await commit(f.isolationDir, "new")
  await writeFile(join(f.repoRoot, "tracked"), "staged\n")
  await git(f.repoRoot, "add", "tracked")
  await writeFile(join(f.repoRoot, "tracked"), "unstaged\n")
  await writeFile(join(f.repoRoot, "untracked"), Buffer.from([0, 255, 2]))
  const staged = await git(f.repoRoot, "diff", "--cached", "--binary")
  const unstaged = await git(f.repoRoot, "diff", "--binary")
  const result = await mergeIsolatedChanges({ ...f, mode: "branch" })
  expect(result.kind).toBe("branch-merged")
  expect(await git(f.repoRoot, "diff", "--cached", "--binary")).toBe(staged)
  expect(await git(f.repoRoot, "diff", "--binary")).toBe(unstaged)
  expect(await readFile(join(f.repoRoot, "untracked"))).toEqual(Buffer.from([0, 255, 2]))
  expect(await git(f.repoRoot, "stash", "list")).toBe("")
})
