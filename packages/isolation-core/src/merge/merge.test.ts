test("linked parent uses common git directory lock", async () => {
  const f = await setup()
  const linked = join(f.root, "linked")
  await git(f.repoRoot, "worktree", "add", "-b", "linked", linked)
  await commit(f.isolationDir, "new")
  let lockPath = ""
  const result = await mergeIsolatedChanges({ ...f, repoRoot: linked, mode: "branch", lockHook: async (event, path) => {
    if (event === "acquired") { lockPath = path; expect((await stat(path)).isFile()).toBe(true) }
  } })
  expect(result.kind).toBe("branch-merged")
  expect(lockPath).toBe(join(await git(linked, "rev-parse", "--path-format=absolute", "--git-common-dir"), "omo-isolation-merge.lock"))
  expect(await text(linked, "new")).toBe("new\n")
})
test.each(["patch", "branch"] as const)("concurrent %s merges serialize acquire/release without timing assertions", async (mode: "patch" | "branch") => {
  const f = await setup()
  await writeFile(join(f.isolationDir, "one"), "one\n")
  const other = join(f.root, "other")
  await cp(f.repoRoot, other, { recursive: true })
  await writeFile(join(other, "two"), "two\n")
  const entered = Promise.withResolvers<void>()
  const release = Promise.withResolvers<void>()
  const queued = Promise.withResolvers<void>()
  const events: string[] = []
  const first = mergeIsolatedChanges({ ...f, mode, lockHook: async event => {
    events.push(`first:${event}`)
    if (event === "acquired") { entered.resolve(); await release.promise }
  } })
  await entered.promise
  const second = mergeIsolatedChanges({ ...f, mode, id: "second", isolationDir: other, lockHook: event => {
    events.push(`second:${event}`)
    if (event === "waiting") queued.resolve()
  } })
  await queued.promise
  release.resolve()
  const results = await Promise.all([first, second])
  const kind = mode === "patch" ? "applied" : "branch-merged"
  expect(results.map(r => r.kind)).toEqual([kind, kind])
  expect(events).toEqual(["first:waiting", "first:acquired", "second:waiting", "first:released", "second:acquired", "second:released"])
  expect(await text(f.repoRoot, "one")).toBe("one\n")
  expect(await text(f.repoRoot, "two")).toBe("two\n")
}, 15000)
test("dirty baseline filters user WIP out of each child commit", async () => {
  const f = await setup()
  await writeFile(join(f.repoRoot, "tracked"), "user WIP\n")
  await writeFile(join(f.repoRoot, "user-file"), "user untracked\n")
  const baseline = await captureBaseline(f.repoRoot)
  const isolationDir = join(f.root, "dirty-child")
  await cp(f.repoRoot, isolationDir, { recursive: true })
  await git(isolationDir, "add", ".")
  await commit(isolationDir, "first")
  await commit(isolationDir, "second")
  const result = await mergeIsolatedChanges({ ...f, baseline, isolationDir, mode: "branch" })
  expect(result.kind).toBe("branch-merged")
  expect(await git(f.repoRoot, "log", "-2", "--format=%s")).toBe("second\nfirst")
  expect(await git(f.repoRoot, "show", "HEAD:tracked")).toBe("base")
  expect(await git(f.repoRoot, "ls-tree", "--name-only", "HEAD")).not.toContain("user-file")
  expect(await text(f.repoRoot)).toBe("user WIP\n")
  expect(await text(f.repoRoot, "user-file")).toBe("user untracked\n")
})
test("dirty baseline overlapping commit fails with typed commit identity and retained branch", async () => {
  const f = await setup()
  await writeFile(join(f.repoRoot, "tracked"), "user WIP\n")
  const baseline = await captureBaseline(f.repoRoot)
  const isolationDir = join(f.root, "dirty-child")
  await cp(f.repoRoot, isolationDir, { recursive: true })
  await commit(isolationDir, "tracked", "overlapping child\n")
  const sha = await git(isolationDir, "rev-parse", "HEAD")
  let failure: unknown
  try { await commitToBranch(isolationDir, f.repoRoot, f.id, baseline) } catch (error) { failure = error }
  expect(failure).toBeInstanceOf(IsolationCommitReplayError)
  expect((failure as IsolationCommitReplayError).commit).toBe(sha)
  expect(await text(f.repoRoot)).toBe("user WIP\n")
  expect(await git(f.repoRoot, "branch", "--list", "omo/task/test")).toContain("omo/task/test")
})

