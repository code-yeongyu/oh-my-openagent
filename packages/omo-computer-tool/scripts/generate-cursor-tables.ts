// Regenerates the agent cursor tables of IS row 52 from crates/omo-computer-session/src/presence/:
// src/cursor-motion.generated.ts and src/cursor-look.generated.ts, plus the byte-equal
// cursor-motion.json and cursor-look.json this package ships.
// Run: bun run --cwd packages/omo-computer-tool generate
import { readFileSync, writeFileSync } from "node:fs"
import { basename, dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..")
const presenceDir = join(packageDir, "../../crates/omo-computer-session/src/presence")

export type CursorTable = {
  readonly source: string
  readonly copy: string
  readonly module: string
  readonly constName: string
  readonly summary: string
}

export const CURSOR_TABLES: readonly CursorTable[] = [
  {
    source: join(presenceDir, "cursor-motion.json"),
    copy: join(packageDir, "cursor-motion.json"),
    module: join(packageDir, "src/cursor-motion.generated.ts"),
    constName: "CURSOR_MOTION",
    summary:
      "The agent cursor's glide: clamp(minMs, maxMs, baseMs + perDoublingMs * log2(1 + d / distanceUnitPoints)) ms.",
  },
  {
    source: join(presenceDir, "cursor-look.json"),
    copy: join(packageDir, "cursor-look.json"),
    module: join(packageDir, "src/cursor-look.generated.ts"),
    constName: "CURSOR_LOOK",
    summary: "The agent cursor's look: the arrow, the halo, the footprint, the session colours and the badges.",
  },
]

/** The generated module's exact text for one table's JSON text. */
export function renderTableModule(table: CursorTable, jsonText: string): string {
  const literal = JSON.stringify(JSON.parse(jsonText), null, "\t")
  return `// GENERATED by scripts/generate-cursor-tables.ts from crates/omo-computer-session/src/presence/${basename(table.source)}.
// Do not edit by hand; run \`bun run --cwd packages/omo-computer-tool generate\`.

/** ${table.summary} */
export const ${table.constName} = ${literal} as const
`
}

if (import.meta.main) {
  for (const table of CURSOR_TABLES) {
    const text = readFileSync(table.source, "utf8")
    writeFileSync(table.copy, text)
    writeFileSync(table.module, renderTableModule(table, text))
  }
}
