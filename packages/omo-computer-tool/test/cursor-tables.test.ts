import { readFileSync } from "node:fs"

import { expect, test } from "vitest"

import { CURSOR_TABLES, renderTableModule } from "../scripts/generate-cursor-tables.ts"
import { CURSOR_LOOK } from "../src/cursor-look.generated.ts"
import { CURSOR_MOTION } from "../src/cursor-motion.generated.ts"

const imported: Readonly<Record<string, unknown>> = { CURSOR_MOTION, CURSOR_LOOK }

test.each(CURSOR_TABLES)("$constName is regenerated byte for byte and ships the crate's table", (table) => {
  const text = readFileSync(table.source, "utf8")
  expect(renderTableModule(table, text)).toBe(readFileSync(table.module, "utf8"))
  expect(readFileSync(table.copy, "utf8")).toBe(text)
  expect(imported[table.constName]).toEqual(JSON.parse(text))
})
